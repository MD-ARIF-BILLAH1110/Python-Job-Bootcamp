import math

result = math.sqrt(25)
pi_result = math.pi
ceil_result = math.ceil(4.2) # near top number 5
floor_result = math.floor(4.9) # near low number 4
power_result = math.pow(2, 5)  # 2 multiply 5 times


print(f"Result: {result}")
print(f"Pi: {pi_result}")
print(f"Ceil: {ceil_result}")
print(f"Floor: {floor_result}")
print(f"Power: {power_result}")